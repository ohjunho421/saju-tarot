export function getDayMasterTrait(dayMaster: unknown): DayMasterTrait | null {
  // 클라이언트가 보낸 사주 값일 수 있어 'constructor' 같은 프로토타입 키를 막는다
  if (typeof dayMaster !== 'string' || !Object.prototype.hasOwnProperty.call(DAY_MASTER_TRAITS, dayMaster)) return null;
  return DAY_MASTER_TRAITS[dayMaster];
}

// 프롬프트에 넣을 일간 성향 블록
export function formatDayMasterTrait(trait: DayMasterTrait): string {
  return [
    `${trait.name}(${trait.hanja}) 일간: ${trait.image}`,
    `본성: ${trait.nature}`,
    `강점: ${trait.strengths.join(', ')}`,
    `지나치면: ${trait.shadows.join(', ')}`,
    `고민이 생기기 쉬운 지점: ${trait.worryPattern}`,
    `와닿는 말 방식: ${trait.reachStyle}`
  ].join('\n');
}
